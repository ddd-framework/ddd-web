import type { OpenApiDocument } from './openapi';
import { listOperations } from './openapi';

export const GENERATED_HEADER = '// AUTO-GENERATED by @mgamadeus/ddd-web (ddd-web-sdk) — do not edit manually.';

/**
 * Normalises an operation tag into a PascalCase identifier, stripping the audience prefix word.
 *   "Admin Google Places" (admin) → "GooglePlaces";  "Admin AI Models" → "AIModels";  "BikeTypes " → "BikeTypes"
 */
export function normalizeTag(tag: string, audiencePrefix?: string): string {
  const parts = tag.trim().split(/\s+/);
  const filtered =
    audiencePrefix && parts[0]?.toLowerCase() === audiencePrefix.toLowerCase() ? parts.slice(1) : parts;
  return filtered
    .filter(Boolean)
    .map((part) => {
      if (part === part.toUpperCase() && part.length > 1) return part;
      return part.charAt(0).toUpperCase() + part.slice(1).toLowerCase();
    })
    .join('');
}

export function collectOperationTags(doc: OpenApiDocument, audience: string): string[] {
  const raw = new Set<string>();
  for (const { operation } of listOperations(doc)) {
    for (const tag of operation.tags ?? []) raw.add(tag);
  }
  return [...new Set([...raw].map((tag) => normalizeTag(tag, audience)).filter(Boolean))].sort();
}

/**
 * Cache tag for an `x-ddd-entity` schema. Prefers an existing operation tag named after the entity's
 * namespace folder or its plural (`…Entities.BikeTypes.BikeType` → `BikeTypes`), so annotated and
 * unannotated operations of one entity share a tag.
 */
export function entityTag(schema: string, knownTags: Map<string, string>): string {
  const parts = schema.replace('#/components/schemas/', '').split('.');
  const leaf = parts[parts.length - 1] ?? schema;
  const folder = parts.length > 1 ? parts[parts.length - 2] : undefined;
  const candidates = [folder, `${leaf}s`, leaf].filter((value): value is string => !!value);
  for (const candidate of candidates) {
    const known = knownTags.get(normalizeTag(candidate).toLowerCase());
    if (known) return known;
  }
  return normalizeTag(folder && folder !== 'Entities' ? folder : leaf);
}

export function tagFileNames(stem: string): { constName: string; typeName: string } {
  return {
    constName: `${stem}TagTypes`,
    typeName: `${stem.charAt(0).toUpperCase()}${stem.slice(1)}TagType`,
  };
}

export function renderTagsFile(stem: string, tags: string[]): string {
  const { constName, typeName } = tagFileNames(stem);
  return [
    GENERATED_HEADER,
    '',
    `export const ${constName} = [`,
    ...tags.map((tag) => `  '${tag}',`),
    '] as const;',
    '',
    `export type ${typeName} = (typeof ${constName})[number];`,
    '',
  ].join('\n');
}

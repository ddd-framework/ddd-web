import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import type { Logger } from './log';

/*
 * Vendor skill links: links the agent skills shipped by DDD packages (`<package>/.claude/skills/<name>/SKILL.md` of
 * every `vendor/mgamadeus/*` and `node_modules/@mgamadeus/*` below the repository root) into `.claude/skills`, mirrors
 * them into existing Codex folders, removes links whose skill is gone, records them in `.ddd-skills.json` and keeps a
 * managed `.gitignore` block. Same behaviour, output and manifest as `ddd-link-skills` of the Composer package
 * mgamadeus/ddd, so the Composer hook and the npm postinstall agree.
 */

export const PRIMARY_SKILLS_DIRECTORY = '.claude/skills';
/** Codex skill folders, mirrored only when they already exist. */
export const MIRROR_SKILLS_DIRECTORIES = ['.agents/skills', '.codex/skills'] as const;
export const SKILLS_MANIFEST_FILE_NAME = '.ddd-skills.json';
export const SKILLS_MANIFEST_FORMAT = 1;
export const SKILLS_GITIGNORE_BLOCK_START = '# ddd-skills:start';
export const SKILLS_GITIGNORE_BLOCK_END = '# ddd-skills:end';
const GITIGNORE_BLOCK_COMMENT = '# Generated by ddd-link-skills / ddd-web link-skills; rewritten on every install.';
/** Deepest level below the root at which a `vendor/` or `node_modules/` folder is searched (`apps/admin/vendor`). */
const MAXIMUM_INSTALL_FOLDER_DEPTH = 3;
export const SKILLS_ROOT_ENV = 'DDD_SKILLS_ROOT';
export const SKILLS_OUTPUT_PREFIX = '[ddd-skills]';

type OperationKind = 'link' | 'relink' | 'remove' | 'write';
const OPERATION_LABELS: Record<OperationKind, [string, string, string]> = {
  link: ['linked', 'would link', 'missing'],
  relink: ['relinked', 'would relink', 'stale'],
  remove: ['removed', 'would remove', 'broken'],
  write: ['updated', 'would update', 'outdated'],
};

interface Operation {
  kind: OperationKind;
  path: string;
  display: string;
  target?: string;
  content?: string;
}

interface SkillCandidate {
  name: string;
  package: string;
  version: string | null;
  directory: string;
}

/** One entry of `.ddd-skills.json` → `skills`. */
export interface SkillsManifestEntry {
  package: string | null;
  version: string | null;
  /** Skill folder relative to the repository root. */
  source: string | null;
  /** Symlink target as written (relative to the primary folder). */
  target: string;
  /** sha256 of SKILL.md when it was linked. */
  sha256: string | null;
  /** Mirror folders (`.agents/skills`, `.codex/skills`) that got a link. */
  mirrors: string[];
}

export interface SkillsManifest {
  format: number;
  skills: Record<string, SkillsManifestEntry>;
}

export interface SkillLinksOptions {
  /** Where the search for the repository root starts. Default `process.cwd()`. */
  cwd?: string;
  /** Repository root; wins over `DDD_SKILLS_ROOT` and the search from `cwd`. */
  root?: string;
  /** Change nothing; report every deviation (exit code 1 on any). */
  check?: boolean;
  /** Change nothing; print what would change. */
  dryRun?: boolean;
  /** Print only warnings and problems. */
  quiet?: boolean;
  logger?: Logger;
  /**
   * @deprecated Kept for callers of 0.16 and older: link only the skills of this folder (package read from the
   * `package.json` two levels up) instead of discovering every DDD package.
   */
  sourceDir?: string;
}

export type LinkSkillAction = 'linked' | 'relinked' | 'unchanged' | 'skipped';

export interface LinkSkillsResult {
  skill: string;
  action: LinkSkillAction;
  target: string;
  package?: string;
}

/** @deprecated Use {@link SkillLinksOptions}. */
export type LinkSkillsOptions = SkillLinksOptions;

export interface SkillLinksReport {
  /** Real path of the repository root. */
  root: string;
  /** 0, or 1 on check problems and on unexpected errors while writing. */
  exitCode: number;
  /** Per discovered skill (also the clashing ones, as `skipped`). */
  skills: LinkSkillsResult[];
  /** Every printed line, without prefix. */
  lines: string[];
  /** Problems (check mode) and warnings. */
  problems: string[];
}

const prefixedConsoleLogger: Logger = {
  info: (message) => console.log(`${SKILLS_OUTPUT_PREFIX} ${message}`),
  warn: (message) => console.warn(`${SKILLS_OUTPUT_PREFIX} ${message}`),
  error: (message) => console.error(`${SKILLS_OUTPUT_PREFIX} ${message}`),
};

const label = (text: string): string => text.padEnd(13);

/**
 * The repository root: the nearest ancestor of `startDirectory` (itself included) that contains `.git` (folder or
 * file), else the nearest that contains `.claude` (the home folder's `.claude` is the user's global configuration and
 * never counts), else `startDirectory` itself.
 */
export function findSkillsRepositoryRoot(startDirectory: string): string {
  const start = realpathOr(path.resolve(startDirectory));
  const home = realpathOr(os.homedir());
  for (const marker of ['.git', '.claude']) {
    let directory = start;
    for (;;) {
      const isHomeClaude = marker === '.claude' && directory === home;
      if (!isHomeClaude && lstatOrNull(path.join(directory, marker))) return directory;
      const parent = path.dirname(directory);
      if (parent === directory) break;
      directory = parent;
    }
  }
  return start;
}

/**
 * Plans and (unless `check` / `dryRun`) applies the vendor skill links, the manifest and the gitignore blocks.
 * Never throws for expected situations; an unexpected write error gives exit code 1.
 */
export function runSkillLinks(options: SkillLinksOptions = {}): SkillLinksReport {
  const logger = options.logger ?? prefixedConsoleLogger;
  const cwd = path.resolve(options.cwd ?? process.cwd());
  const envRoot = process.env[SKILLS_ROOT_ENV];
  const requestedRoot = options.root ? path.resolve(cwd, options.root) : envRoot ? path.resolve(cwd, envRoot) : findSkillsRepositoryRoot(cwd);
  const linker = new SkillLinker(requestedRoot, options, logger);
  return linker.run();
}

/**
 * Links the agent skills of every installed DDD package into the repository's `.claude/skills` (see
 * {@link runSkillLinks}); returns one result per discovered skill. Kept for callers of 0.16 and older.
 */
export function linkSkills(options: SkillLinksOptions = {}): LinkSkillsResult[] {
  return runSkillLinks(options).skills;
}

class SkillLinker {
  protected readonly root: string;
  protected readonly modeIndex: number;
  protected readonly lines: string[] = [];
  protected readonly problems: string[] = [];
  protected readonly results: LinkSkillsResult[] = [];

  constructor(
    rootDirectory: string,
    protected readonly options: SkillLinksOptions,
    protected readonly logger: Logger,
  ) {
    this.root = realpathOr(rootDirectory);
    this.modeIndex = options.check ? 2 : options.dryRun ? 1 : 0;
  }

  run(): SkillLinksReport {
    if (!isDirectory(this.root)) {
      this.warn(`error: the root directory ${this.root} does not exist`);
      return this.report(1);
    }
    let plan: ReturnType<SkillLinker['createPlan']>;
    try {
      plan = this.createPlan();
    } catch (error) {
      this.warn(`error: ${(error as Error).message}`);
      return this.report(1);
    }
    if (plan.nothingToDo) {
      this.info(`no DDD package ships agent skills below ${this.root}; nothing to link`);
      return this.report(0);
    }
    this.problems.push(...plan.warnings);
    if (!this.options.check && !this.options.dryRun) {
      try {
        this.applyOperations(plan.operations);
      } catch (error) {
        this.warn(`error: ${(error as Error).message}`);
        return this.report(1);
      }
    }
    for (const operation of plan.operations) {
      const line = label(OPERATION_LABELS[operation.kind][this.modeIndex]!) + operation.display;
      if (this.options.check) {
        this.problems.push(line);
        this.warn(line);
      } else if (!this.options.quiet) {
        this.print(line, 'info');
      }
    }
    for (const warning of plan.warnings) this.warn(warning);
    const skillCount = plan.managedSkillNames.length;
    const packageCount = plan.packageNames.length;
    const changeCount = plan.operations.length;
    if (this.options.check) {
      if (this.problems.length > 0) {
        this.warn(`check failed: ${this.problems.length} problem(s); run ddd-link-skills (or ddd-web link-skills) to fix the links`);
        return this.report(1);
      }
      this.info(`check passed: ${skillCount} skill(s) from ${packageCount} package(s)`);
      return this.report(0);
    }
    if (this.options.dryRun) {
      this.info(`dry run: ${changeCount} change(s) would be made`);
      return this.report(0);
    }
    this.info(`${skillCount} skill(s) from ${packageCount} package(s), ${changeCount} change(s)`);
    return this.report(0);
  }

  protected report(exitCode: number): SkillLinksReport {
    return { root: this.root, exitCode, skills: this.results, lines: this.lines, problems: this.problems };
  }

  protected createPlan(): {
    nothingToDo: boolean;
    operations: Operation[];
    warnings: string[];
    managedSkillNames: string[];
    packageNames: string[];
  } {
    const operations: Operation[] = [];
    const discovery = this.discoverSkills();
    const warnings: string[] = [...discovery.warnings];
    const winners = discovery.winners;

    const primaryLogical = `${this.root}/${PRIMARY_SKILLS_DIRECTORY}`;
    const primary = this.resolvePrimaryDirectory();
    const primaryExists = isDirectory(primaryLogical);
    if (!primaryExists && winners.size === 0) {
      return { nothingToDo: true, operations: [], warnings: [], managedSkillNames: [], packageNames: [] };
    }
    const previousManifestPath = `${primary}/${SKILLS_MANIFEST_FILE_NAME}`;
    let previousEntries = readManifestEntries(previousManifestPath);
    if (previousEntries === null) {
      warnings.push(`${label('manifest')}${this.displayPath(previousManifestPath)} is not readable; rewritten`);
      previousEntries = {};
    }

    const managed = new Map<string, SkillsManifestEntry>();
    for (const [skillName, skill] of winners) {
      const linkPath = `${primary}/${skillName}`;
      const desiredTarget = relativePath(primary, skill.directory);
      const display = `${PRIMARY_SKILLS_DIRECTORY}/${skillName}`;
      const entryType = getEntryType(linkPath);
      let action: LinkSkillAction = 'unchanged';
      if (entryType === 'missing') {
        operations.push({ kind: 'link', path: linkPath, target: desiredTarget, display: `${display} -> ${desiredTarget}` });
        action = 'linked';
      } else if (entryType === 'link') {
        const currentTarget = fs.readlinkSync(linkPath);
        if (currentTarget !== desiredTarget) {
          if (!isDddVendorPath(resolveLinkTarget(primary, currentTarget))) {
            warnings.push(`${label('clash')}${display}: a symlink of the app to ${currentTarget} exists; the skill of ${skill.package} is not linked`);
            this.results.push({ skill: skillName, action: 'skipped', target: desiredTarget, package: skill.package });
            continue;
          }
          operations.push({ kind: 'relink', path: linkPath, target: desiredTarget, display: `${display} -> ${desiredTarget} (was ${currentTarget})` });
          action = 'relinked';
        }
      } else {
        warnings.push(`${label('clash')}${display}: the app has its own skill of this name; the skill of ${skill.package} is not linked`);
        this.results.push({ skill: skillName, action: 'skipped', target: desiredTarget, package: skill.package });
        continue;
      }
      this.results.push({ skill: skillName, action, target: desiredTarget, package: skill.package });
      let skillFileHash = createHash('sha256').update(fs.readFileSync(`${skill.directory}/SKILL.md`)).digest('hex');
      const previous = previousEntries[skillName];
      if (
        previous &&
        previous.package === skill.package &&
        skill.version !== null &&
        previous.version === skill.version &&
        typeof previous.sha256 === 'string' &&
        previous.sha256 !== skillFileHash
      ) {
        warnings.push(
          `${label('edited')}${skillName}: SKILL.md of ${skill.package} ${skill.version} differs from the installed copy recorded in the manifest`,
        );
        skillFileHash = previous.sha256;
      }
      managed.set(skillName, {
        package: skill.package,
        version: skill.version,
        source: relativePath(this.root, skill.directory),
        target: desiredTarget,
        sha256: skillFileHash,
        mirrors: [],
      });
    }

    // Former entries: keep those still resolving (another install tree)
    for (const [skillName, previous] of Object.entries(previousEntries)) {
      if (managed.has(skillName) || winners.has(skillName) || !previous || typeof previous !== 'object') continue;
      const linkPath = `${primary}/${skillName}`;
      if (getEntryType(linkPath) !== 'link') continue;
      const currentTarget = fs.readlinkSync(linkPath);
      if (!isDddVendorPath(resolveLinkTarget(primary, currentTarget))) continue;
      if (fs.existsSync(linkPath)) {
        managed.set(skillName, {
          package: previous.package ?? null,
          version: previous.version ?? null,
          source: previous.source ?? null,
          target: currentTarget,
          sha256: previous.sha256 ?? null,
          mirrors: [],
        });
      }
    }
    // Broken links into a DDD vendor area (skill no longer shipped, package removed)
    const removedNames = new Set<string>();
    for (const entryName of listDirectoryNames(primary)) {
      const linkPath = `${primary}/${entryName}`;
      if (managed.has(entryName) || getEntryType(linkPath) !== 'link' || fs.existsSync(linkPath)) continue;
      const currentTarget = fs.readlinkSync(linkPath);
      if (isDddVendorPath(resolveLinkTarget(primary, currentTarget))) {
        removedNames.add(entryName);
        operations.push({ kind: 'remove', path: linkPath, display: `${PRIMARY_SKILLS_DIRECTORY}/${entryName} (broken link to ${currentTarget})` });
      }
    }
    const managedNames = [...managed.keys()].sort(compareBytes);

    // Mirrors
    const mirrorGitignoreNames = new Map<string, string[]>();
    const gitPaths: string[] = [];
    for (const mirrorName of MIRROR_SKILLS_DIRECTORIES) {
      const mirrorLogical = `${this.root}/${mirrorName}`;
      if (getEntryType(mirrorLogical) === 'missing' || !isDirectory(mirrorLogical)) continue;
      const mirror = realpathOr(mirrorLogical);
      const mirrorParent = realpathOr(path.dirname(mirrorLogical));
      if (mirror === primary || mirrorParent === primary) continue;
      mirrorGitignoreNames.set(mirror, []);
      for (const skillName of managedNames) {
        const linkPath = `${mirror}/${skillName}`;
        const primaryEntryPath = `${primaryLogical}/${skillName}`;
        const desiredTarget = relativePath(mirror, primaryEntryPath);
        const display = `${mirrorName}/${skillName}`;
        const entryType = getEntryType(linkPath);
        if (entryType === 'missing') {
          operations.push({ kind: 'link', path: linkPath, target: desiredTarget, display: `${display} -> ${desiredTarget}` });
        } else if (entryType === 'link') {
          const currentTarget = fs.readlinkSync(linkPath);
          if (currentTarget !== desiredTarget) {
            const resolvedTarget = resolveLinkTarget(mirror, currentTarget);
            const pointsToPrimary = resolvedTarget === primaryEntryPath || resolvedTarget === `${primary}/${skillName}`;
            if (!pointsToPrimary && !isDddVendorPath(resolvedTarget)) {
              warnings.push(`${label('clash')}${display}: a symlink of the app to ${currentTarget} exists; not mirrored`);
              continue;
            }
            operations.push({ kind: 'relink', path: linkPath, target: desiredTarget, display: `${display} -> ${desiredTarget} (was ${currentTarget})` });
          }
        } else {
          warnings.push(`${label('clash')}${display}: the app has its own skill of this name; not mirrored`);
          continue;
        }
        managed.get(skillName)!.mirrors.push(mirrorName);
        mirrorGitignoreNames.get(mirror)!.push(skillName);
        gitPaths.push(linkPath);
      }
      // Mirror cleanup: broken DDD links and links to primary entries that are gone
      for (const entryName of listDirectoryNames(mirror)) {
        const linkPath = `${mirror}/${entryName}`;
        if (managed.has(entryName) || getEntryType(linkPath) !== 'link') continue;
        const currentTarget = fs.readlinkSync(linkPath);
        const resolvedTarget = resolveLinkTarget(mirror, currentTarget);
        const pointsToPrimary = resolvedTarget === `${primaryLogical}/${entryName}` || resolvedTarget === `${primary}/${entryName}`;
        const isBrokenDddLink = !fs.existsSync(linkPath) && isDddVendorPath(resolvedTarget);
        const isFormerMirror =
          pointsToPrimary &&
          (removedNames.has(entryName) || entryName in previousEntries) &&
          (!fs.existsSync(`${primary}/${entryName}`) || removedNames.has(entryName));
        if (isBrokenDddLink || isFormerMirror) {
          operations.push({ kind: 'remove', path: linkPath, display: `${mirrorName}/${entryName} (link to removed ${currentTarget})` });
        }
      }
    }

    // Manifest
    const manifestPath = `${primary}/${SKILLS_MANIFEST_FILE_NAME}`;
    const manifestContent = encodeManifest(managedNames, managed);
    if ((isFile(manifestPath) ? fs.readFileSync(manifestPath, 'utf-8') : null) !== manifestContent) {
      operations.push({ kind: 'write', path: manifestPath, content: manifestContent, display: `${PRIMARY_SKILLS_DIRECTORY}/${SKILLS_MANIFEST_FILE_NAME}` });
    }

    // Gitignore blocks
    const primaryGitignoreEntries = [`/${SKILLS_MANIFEST_FILE_NAME}`];
    for (const skillName of managedNames) {
      primaryGitignoreEntries.push(`/${skillName}`);
      gitPaths.push(`${primary}/${skillName}`);
    }
    gitPaths.push(manifestPath);
    const gitignoreTargets = new Map<string, string[]>([[primary, primaryGitignoreEntries]]);
    for (const [mirror, names] of mirrorGitignoreNames) {
      gitignoreTargets.set(mirror, [...names].sort(compareBytes).map((name) => `/${name}`));
    }
    for (const [directory, entries] of gitignoreTargets) {
      const gitignorePath = `${directory}/.gitignore`;
      const currentContent = isFile(gitignorePath) ? fs.readFileSync(gitignorePath, 'utf-8') : null;
      const newContent = createGitignoreContent(currentContent, entries);
      if (newContent === null) {
        warnings.push(
          `${label('gitignore')}${this.displayPath(gitignorePath)}: ${SKILLS_GITIGNORE_BLOCK_START} without ${SKILLS_GITIGNORE_BLOCK_END}; left as is`,
        );
      } else if (newContent !== (currentContent ?? '')) {
        operations.push({ kind: 'write', path: gitignorePath, content: newContent, display: this.displayPath(gitignorePath) });
      }
    }

    // Generated links still tracked by git
    const trackedPaths = this.findTrackedPaths(gitPaths);
    if (trackedPaths.length > 0) {
      warnings.push(
        `${label('tracked')}${trackedPaths.length} generated path(s) are still tracked by git; run in ${this.root}: ` +
          `git rm --cached -- ${trackedPaths.map(quoteShellArgument).join(' ')} (then commit with the updated .gitignore)`,
      );
    }

    const packageNames = new Set<string>();
    for (const entry of managed.values()) if (typeof entry.package === 'string') packageNames.add(entry.package);
    return { nothingToDo: false, operations, warnings, managedSkillNames: managedNames, packageNames: [...packageNames] };
  }

  /**
   * Skills of all DDD packages below the root in deterministic order (skill path, byte order). The first package
   * shipping a name wins; another package with the same name is a clash; the same package installed twice is not.
   */
  protected discoverSkills(): { winners: Map<string, SkillCandidate>; warnings: string[] } {
    const candidates: SkillCandidate[] = [];
    const packages = this.options.sourceDir ? [this.legacySourcePackage(this.options.sourceDir)] : this.findPackages(this.root, 0);
    for (const pkg of packages) {
      const skillsDirectory = pkg.skillsDirectory;
      for (const skillName of listDirectoryNames(skillsDirectory)) {
        const skillDirectory = `${skillsDirectory}/${skillName}`;
        if (skillName.startsWith('.') || !isDirectory(skillDirectory) || !isFile(`${skillDirectory}/SKILL.md`)) continue;
        candidates.push({ name: skillName, package: pkg.package, version: pkg.version, directory: skillDirectory });
      }
    }
    candidates.sort((first, second) => compareBytes(first.directory, second.directory));
    const winners = new Map<string, SkillCandidate>();
    const warnings: string[] = [];
    for (const candidate of candidates) {
      const winner = winners.get(candidate.name);
      if (!winner) {
        winners.set(candidate.name, candidate);
      } else if (winner.package !== candidate.package) {
        warnings.push(
          `${label('clash')}${candidate.name}: shipped by ${winner.package} (${relativePath(this.root, winner.directory)}) and ` +
            `${candidate.package} (${relativePath(this.root, candidate.directory)}); ${winner.package} kept`,
        );
        this.results.push({ skill: candidate.name, action: 'skipped', target: relativePath(this.root, candidate.directory), package: candidate.package });
      }
    }
    return { winners, warnings };
  }

  protected legacySourcePackage(sourceDir: string): { package: string; version: string | null; skillsDirectory: string } {
    const skillsDirectory = path.resolve(path.resolve(this.options.cwd ?? process.cwd()), sourceDir);
    const packageJson = readJson(path.join(skillsDirectory, '..', '..', 'package.json'));
    return {
      package: typeof packageJson?.name === 'string' ? packageJson.name : '@mgamadeus/ddd-web',
      version: typeof packageJson?.version === 'string' ? packageJson.version : null,
      skillsDirectory,
    };
  }

  protected findPackages(directory: string, depth: number): { package: string; version: string | null; skillsDirectory: string }[] {
    const packages: { package: string; version: string | null; skillsDirectory: string }[] = [];
    const composerScope = `${directory}/vendor/mgamadeus`;
    if (isDirectory(composerScope)) {
      const installedVersions = readComposerInstalledVersions(`${directory}/vendor/composer/installed.json`);
      for (const folderName of listDirectoryNames(composerScope)) {
        const packageDirectory = `${composerScope}/${folderName}`;
        if (!isDirectory(packageDirectory)) continue;
        const packageName = `mgamadeus/${folderName}`;
        packages.push({
          package: packageName,
          version: installedVersions.get(packageName) ?? readJsonVersion(`${packageDirectory}/composer.json`),
          skillsDirectory: `${packageDirectory}/.claude/skills`,
        });
      }
    }
    const npmScope = `${directory}/node_modules/@mgamadeus`;
    if (isDirectory(npmScope)) {
      for (const folderName of listDirectoryNames(npmScope)) {
        const packageDirectory = `${npmScope}/${folderName}`;
        if (!isDirectory(packageDirectory)) continue;
        packages.push({
          package: `@mgamadeus/${folderName}`,
          version: readJsonVersion(`${packageDirectory}/package.json`),
          skillsDirectory: `${packageDirectory}/.claude/skills`,
        });
      }
    }
    if (depth + 1 >= MAXIMUM_INSTALL_FOLDER_DEPTH) return packages;
    for (const childName of listDirectoryNames(directory)) {
      const childDirectory = `${directory}/${childName}`;
      if (childName.startsWith('.') || childName === 'vendor' || childName === 'node_modules') continue;
      const childStat = lstatOrNull(childDirectory);
      if (!childStat || !childStat.isDirectory()) continue;
      packages.push(...this.findPackages(childDirectory, depth + 1));
    }
    return packages;
  }

  /** Real location of `<root>/.claude/skills`, also when it does not exist yet (then `.claude` resolved). */
  protected resolvePrimaryDirectory(): string {
    const claude = `${this.root}/.claude`;
    const primaryLogical = `${this.root}/${PRIMARY_SKILLS_DIRECTORY}`;
    if (isDirectory(primaryLogical)) return realpathOr(primaryLogical);
    if (lstatOrNull(primaryLogical)) throw new Error(`${PRIMARY_SKILLS_DIRECTORY} exists but is not a folder (broken symlink?)`);
    if (isDirectory(claude)) return `${realpathOr(claude)}/skills`;
    if (lstatOrNull(claude)) throw new Error('.claude exists but is not a folder (broken symlink?)');
    return primaryLogical;
  }

  protected findTrackedPaths(absolutePaths: string[]): string[] {
    const relativePaths = absolutePaths.filter((p) => p.startsWith(`${this.root}/`)).map((p) => p.slice(this.root.length + 1));
    if (relativePaths.length === 0) return [];
    const result = spawnSync('git', ['-C', this.root, 'ls-files', '-z', '--', ...relativePaths], { encoding: 'utf-8' });
    if (result.error || result.status !== 0) return [];
    return [...new Set(result.stdout.split('\0').filter((p) => p !== ''))].sort(compareBytes);
  }

  protected applyOperations(operations: Operation[]): void {
    const primary = this.resolvePrimaryDirectory();
    fs.mkdirSync(primary, { recursive: true });
    for (const kind of ['remove', 'relink', 'link', 'write'] as const) {
      for (const operation of operations) {
        if (operation.kind !== kind) continue;
        if (kind === 'remove' || kind === 'relink') fs.unlinkSync(operation.path);
        if (kind === 'relink' || kind === 'link') fs.symlinkSync(operation.target!, operation.path, 'dir');
        if (kind === 'write') fs.writeFileSync(operation.path, operation.content!);
      }
    }
  }

  protected displayPath(absolutePath: string): string {
    return absolutePath.startsWith(`${this.root}/`) ? absolutePath.slice(this.root.length + 1) : absolutePath;
  }

  protected info(line: string): void {
    if (!this.options.quiet) this.print(line, 'info');
  }

  protected warn(line: string): void {
    this.print(line, 'warn');
  }

  protected print(line: string, level: 'info' | 'warn'): void {
    this.lines.push(line);
    this.logger[level](line);
  }
}

function readManifestEntries(manifestPath: string): Record<string, Partial<SkillsManifestEntry>> | null {
  if (!isFile(manifestPath)) return {};
  const manifest = readJson(manifestPath);
  if (!manifest || typeof manifest.skills !== 'object' || manifest.skills === null || Array.isArray(manifest.skills)) return null;
  return manifest.skills as Record<string, Partial<SkillsManifestEntry>>;
}

/** The manifest exactly as both implementations write it: 4-space JSON, sorted names, trailing newline. */
function encodeManifest(sortedNames: string[], entries: Map<string, SkillsManifestEntry>): string {
  const skills: Record<string, SkillsManifestEntry> = {};
  for (const name of sortedNames) {
    const entry = entries.get(name)!;
    skills[name] = {
      package: entry.package,
      version: entry.version,
      source: entry.source,
      target: entry.target,
      sha256: entry.sha256,
      mirrors: [...entry.mirrors].sort(compareBytes),
    };
  }
  const manifest: SkillsManifest = { format: SKILLS_MANIFEST_FORMAT, skills };
  return `${JSON.stringify(manifest, null, 4)}\n`;
}

/**
 * New content of a .gitignore with the managed block set to `entries` (block removed when empty); everything outside
 * the block is kept. `null` when a start marker has no end marker (the file is left alone).
 */
function createGitignoreContent(currentContent: string | null, entries: string[]): string | null {
  const lines = currentContent === null || currentContent === '' ? [] : currentContent.replace(/\n+$/, '').split('\n');
  const startIndex = lines.indexOf(SKILLS_GITIGNORE_BLOCK_START);
  const block = entries.length > 0 ? [SKILLS_GITIGNORE_BLOCK_START, GITIGNORE_BLOCK_COMMENT, ...entries, SKILLS_GITIGNORE_BLOCK_END] : [];
  if (startIndex === -1) {
    if (block.length === 0) return currentContent ?? '';
    if (lines.length > 0 && lines[lines.length - 1] !== '') lines.push('');
    return `${[...lines, ...block].join('\n')}\n`;
  }
  const endIndex = lines.indexOf(SKILLS_GITIGNORE_BLOCK_END, startIndex + 1);
  if (endIndex === -1) return null;
  const before = lines.slice(0, startIndex);
  const after = lines.slice(endIndex + 1);
  if (block.length === 0 && before.length > 0 && before[before.length - 1] === '') before.pop();
  const newLines = [...before, ...block, ...after];
  return newLines.length > 0 ? `${newLines.join('\n')}\n` : '';
}

function readComposerInstalledVersions(installedJsonPath: string): Map<string, string> {
  const versions = new Map<string, string>();
  const installed = readJson(installedJsonPath) as unknown;
  const list = Array.isArray(installed) ? installed : (installed as { packages?: unknown } | null)?.packages;
  if (!Array.isArray(list)) return versions;
  for (const item of list) {
    if (item && typeof item.name === 'string' && typeof item.version === 'string') versions.set(item.name, item.version);
  }
  return versions;
}

function readJsonVersion(jsonPath: string): string | null {
  const decoded = readJson(jsonPath);
  return typeof decoded?.version === 'string' ? decoded.version : null;
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function readJson(jsonPath: string): any {
  try {
    return JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
  } catch {
    return null;
  }
}

function getEntryType(entryPath: string): 'missing' | 'link' | 'directory' | 'file' {
  const stat = lstatOrNull(entryPath);
  if (!stat) return 'missing';
  if (stat.isSymbolicLink()) return 'link';
  return stat.isDirectory() ? 'directory' : 'file';
}

function lstatOrNull(entryPath: string): fs.Stats | null {
  try {
    return fs.lstatSync(entryPath);
  } catch {
    return null;
  }
}

function isDirectory(entryPath: string): boolean {
  try {
    return fs.statSync(entryPath).isDirectory();
  } catch {
    return false;
  }
}

function isFile(entryPath: string): boolean {
  try {
    return fs.statSync(entryPath).isFile();
  } catch {
    return false;
  }
}

function realpathOr(entryPath: string): string {
  try {
    return fs.realpathSync(entryPath);
  } catch {
    return entryPath;
  }
}

/** Entry names of a folder in byte order; empty when it cannot be read. */
function listDirectoryNames(directory: string): string[] {
  try {
    return fs.readdirSync(directory).sort(compareBytes);
  } catch {
    return [];
  }
}

function compareBytes(first: string, second: string): number {
  return Buffer.compare(Buffer.from(first), Buffer.from(second));
}

/** True when a path lies inside a `vendor/mgamadeus/` or `node_modules/@mgamadeus/` folder. */
function isDddVendorPath(candidate: string): boolean {
  const withSlash = `${candidate}/`;
  return withSlash.includes('/vendor/mgamadeus/') || withSlash.includes('/node_modules/@mgamadeus/');
}

/** Absolute, lexically normalised target of a symlink (no filesystem access, works for broken links). */
function resolveLinkTarget(linkDirectory: string, target: string): string {
  return path.posix.resolve(linkDirectory, target);
}

function relativePath(fromDirectory: string, toPath: string): string {
  return path.posix.relative(fromDirectory, toPath) || '.';
}

function quoteShellArgument(argument: string): string {
  return /^[A-Za-z0-9._/@+=:-]+$/.test(argument) ? argument : `'${argument.replace(/'/g, "'\\''")}'`;
}
